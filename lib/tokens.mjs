// Brand book (wiki/brand-identity.md) → token object → CSS. Fails loudly when the book's tables change shape,
// so a silent half-parse can never ship wrong colors.

const HEX = /#[0-9A-Fa-f]{6}\b/g;
// Role names of the type scale, smallest to largest (ux.md §2)
const SCALE_ROLES = ['body', 'h3', 'h2', 'h1', 'display', 'stat'];
const WEIGHT_ROLES = ['body', 'heading', 'hero'];

function section(md, heading) {
  const start = md.indexOf(heading);
  if (start < 0) throw new Error(`brand book: section "${heading}" not found`);
  const rest = md.slice(start + heading.length);
  const end = rest.search(/\n#{2,3} /);
  return end < 0 ? rest : rest.slice(0, end);
}

const rows = (text) => text.split('\n')
  .filter(l => l.startsWith('|') && !/^\|[\s|:-]+\|?$/.test(l))
  .map(l => l.split('|').slice(1, -1).map(c => c.trim()));

function primitives(md) {
  const out = {};
  for (const [name, value] of rows(section(md, '### Primitive-токены'))) {
    const hexes = value.match(HEX) ?? [];
    const key = name.match(/^`([a-z-]+)`$/)?.[1];
    if (key && hexes.length === 1) out[key] = hexes[0].toUpperCase();
    else if (!key && hexes.length > 1) hexes.forEach((h, i) => { out[`neutral-${i + 1}`] = h.toUpperCase(); });
  }
  if (!Object.keys(out).length) throw new Error('brand book: no primitive tokens parsed');
  return out;
}

function semantic(md, heading) {
  const out = {};
  for (const [names, values] of rows(section(md, heading))) {
    const keys = [...names.matchAll(/`(--[a-z-]+)`/g)].map(m => m[1]);
    if (!keys.length) continue;
    const hexes = values.match(HEX) ?? [];
    if (hexes.length !== keys.length) throw new Error(`brand book: ${heading}: ${keys.join(', ')} have ${hexes.length} values`);
    keys.forEach((k, i) => { out[k] = hexes[i].toUpperCase(); });
  }
  if (!Object.keys(out).length) throw new Error(`brand book: no tokens in "${heading}"`);
  return out;
}

function typography(md) {
  const text = section(md, '## Шрифт и типографика');
  const family = text.match(/\*\*([A-Z][A-Za-z ]+)\*\* \(sans-serif\)/)?.[1];
  const fallback = text.match(/Fallback: `([^`]+)`/)?.[1];
  const scaleLine = text.split('\n').find(l => l.includes('Шкала')) ?? '';
  const scale = [...scaleLine.matchAll(/\b(\d{2})(?:px)?\b/g)].map(m => Number(m[1]));
  const weightLine = text.split('\n').find(l => l.includes('Веса')) ?? '';
  const weights = [...weightLine.matchAll(/\b([1-9]00)\b/g)].map(m => Number(m[1]));
  if (!family || !fallback) throw new Error('brand book: font family or fallback not found');
  if (scale.length !== SCALE_ROLES.length) throw new Error(`brand book: type scale has ${scale.length} steps, expected ${SCALE_ROLES.length}`);
  if (weights.length !== WEIGHT_ROLES.length) throw new Error(`brand book: ${weights.length} font weights, expected ${WEIGHT_ROLES.length}`);
  return {
    family,
    stack: [family, ...fallback.split(',').map(s => s.trim())].map(f => (/\s/.test(f) || f === family) ? `"${f}"` : f).join(', '),
    scale: Object.fromEntries(SCALE_ROLES.map((r, i) => [r, scale[i]])),
    weights: Object.fromEntries(WEIGHT_ROLES.map((r, i) => [r, weights[i]])),
  };
}

export function parseBrand(md) {
  return {
    source: 'wiki/brand-identity.md',
    primitives: primitives(md),
    light: semantic(md, '### Semantic-токены — светлая тема'),
    dark: semantic(md, '### Semantic-токены — тёмная тема'),
    type: typography(md),
  };
}

const block = (vars, indent) => Object.entries(vars).map(([k, v]) => `${indent}${k}: ${v};`).join('\n');

export function renderCss(brand) {
  const base = {
    ...Object.fromEntries(Object.entries(brand.primitives).map(([k, v]) => [`--mik-${k}`, v])),
    '--mik-font': brand.type.stack,
    ...Object.fromEntries(Object.entries(brand.type.scale).map(([k, v]) => [`--mik-fs-${k}`, `${v}px`])),
    ...Object.fromEntries(Object.entries(brand.type.weights).map(([k, v]) => [`--mik-fw-${k}`, v])),
  };
  const dark = { 'color-scheme': 'dark', ...brand.dark };
  return `/* GENERATED by mik-kit (scripts/gen-tokens.mjs) from ${brand.source} — do not edit by hand.
   Light theme by default; dark follows the system unless <html data-theme="light">, or is forced by data-theme="dark". */
:root {
${block({ 'color-scheme': 'light', ...base, ...brand.light }, '  ')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block(dark, '    ')}
  }
}
:root[data-theme="dark"] {
${block(dark, '  ')}
}
`;
}
