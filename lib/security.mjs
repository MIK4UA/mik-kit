// Security headers + CSP for every MIK HTML response (core.md B3, site-standards.md §0.1 item 3).
// One builder → three outputs: an object for Node servers, an nginx include, and a live checker.

// Directives every MIK product starts from; products only ADD sources (after grepping their bundle).
const BASE_CSP = {
  'default-src': ["'self'"],
  'img-src': ["'self'", 'data:'],        // Vite inlines small images as data: URIs
  'font-src': ["'self'"],
  'object-src': ["'none'"],
  'base-uri': ["'self'"],
  'frame-ancestors': ["'none'"],
  'form-action': ["'self'"],
};

export const REQUIRED_HEADERS = {
  'x-content-type-options': 'nosniff',
  'x-frame-options': 'DENY',
  'referrer-policy': 'strict-origin-when-cross-origin',
};
// Directives the live check insists on (a CSP without them is not ours)
export const REQUIRED_CSP = { 'default-src': "'self'", 'frame-ancestors': "'none'", 'object-src': "'none'", 'base-uri': "'self'" };

// extra: { 'connect-src': ['https://n8n.mik4ua.pp.ua'], 'script-src': [...], ... } — added on top of BASE_CSP
export function buildCsp(extra = {}) {
  const csp = structuredClone(BASE_CSP);
  for (const [dir, sources] of Object.entries(extra)) {
    if (!/^[a-z-]+$/.test(dir)) throw new Error(`csp: bad directive "${dir}"`);
    for (const s of [sources].flat()) {
      if (/[;\s"]/.test(s)) throw new Error(`csp: bad source "${s}" in ${dir}`);
      csp[dir] = [...new Set([...(csp[dir] ?? []), s])];
    }
  }
  return Object.entries(csp).map(([d, s]) => `${d} ${s.join(' ')}`).join('; ');
}

// HSTS is not set anywhere yet — the decision is in Ф4 (TZ 2026-10-24-system-unity); opt in with { hsts: true }.
export function securityHeaders({ csp = {}, hsts = false } = {}) {
  const h = {
    'Content-Security-Policy': buildCsp(csp),
    'X-Content-Type-Options': REQUIRED_HEADERS['x-content-type-options'],
    'X-Frame-Options': REQUIRED_HEADERS['x-frame-options'],
    'Referrer-Policy': REQUIRED_HEADERS['referrer-policy'],
  };
  if (hsts) h['Strict-Transport-Security'] = 'max-age=31536000; includeSubDomains';
  return h;
}

// nginx include. Include it in the server block AND in every location that has its own add_header:
// nginx drops all server-level add_header in a location that declares any (mik4ua had zero headers until 24.10.2026).
export function nginxHeaders(opts) {
  const lines = Object.entries(securityHeaders(opts)).map(([k, v]) => `add_header ${k} "${v}" always;`);
  return `# GENERATED by mik-kit (mik-kit nginx-headers) — do not edit, regenerate from mik-kit.config.mjs\n${lines.join('\n')}\n`;
}

// Live check of one response's headers (fetch Headers or a plain object). Returns a list of problems.
export function auditHeaders(headers) {
  const get = (k) => (typeof headers.get === 'function' ? headers.get(k) : headers[k]) ?? null;
  const problems = [];
  for (const [k, v] of Object.entries(REQUIRED_HEADERS)) {
    const got = get(k);
    if (got === null) problems.push(`missing ${k}`);
    else if (got.toLowerCase() !== v.toLowerCase()) problems.push(`${k} is "${got}", expected "${v}"`);
  }
  const csp = get('content-security-policy');
  if (csp === null) problems.push('missing content-security-policy');
  else {
    const dirs = Object.fromEntries(csp.split(';').map(d => d.trim().split(/\s+/)).filter(p => p[0]).map(([d, ...s]) => [d, s]));
    for (const [d, s] of Object.entries(REQUIRED_CSP)) {
      if (!dirs[d]?.includes(s)) problems.push(`csp: ${d} must include ${s}`);
    }
  }
  return problems;
}
